#!/usr/bin/env bash
# Build the throwaway demo world used by the README screenshots.
#
#   ./.README.assets/tools/setup.sh
#
# The world lives in /tmp/fist-demo and is presented to the app as /home/dev by
# capture.sh, so screenshots show clean paths. Your real ~/.config/fist and
# ~/.local/state/fist are never touched.
set -euo pipefail

TOOLS=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$TOOLS/../.." && pwd)
DEMO=${DEMO:-/tmp/fist-demo}
DHOME=$DEMO/home
OVERLAY=$DEMO/overlay-home
CACHE=$DEMO/cache
W=$DHOME/work

need() { command -v "$1" >/dev/null || { echo "missing dependency: $1" >&2; exit 1; }; }
for c in bwrap Xvfb xdotool import chromium magick sqlite3 curl git tar ps2pdf 7z; do need "$c"; done
[ -x "$REPO/target/release/fs" ] || { echo "build the release binary first: cargo build --release" >&2; exit 1; }
CS_DIR=${COMMANDSPACE_DIR:-$REPO/../commandspace}
[ -x "$CS_DIR/target/release/commandspace" ] || { echo "build CommandSpace first (target/release/commandspace not found)" >&2; exit 1; }
if [ ! -x "$CS_DIR/target/release/commandspace-shot" ]; then
  echo "building commandspace-shot"
  (cd "$CS_DIR" && cargo build --release -p commandspace-shot)
fi

echo "resetting $DEMO"
rm -rf "$DHOME" "$OVERLAY"
mkdir -p "$DHOME/.config/fist" "$DHOME/.config/commandspace" \
  "$DHOME/.local/state/fist" "$DHOME/.local/state/commandspace" \
  "$DHOME/.cache/fist" "$DHOME/.local/share" "$DHOME/run" "$DHOME/tmp" \
  "$DHOME/tools-repo" "$OVERLAY/dev" "$CACHE"

# ---- fist config (shipped defaults) ----
cp "$REPO"/assets/config/*.toml "$DHOME/.config/fist/"
cp -r "$REPO"/assets/actions "$DHOME/.config/fist/actions" 2>/dev/null || true
# Demo-only labels for the two history panes. The shipped config uses the
# plain clock prompt (◷>); replace those lines with labeled versions here.
sed -i '/^\[panes.files\]$/,/^\[/ s/^prompt = .*/prompt = "◷ files> "/' "$DHOME/.config/fist/config.toml"
sed -i '/^\[panes.dirs\]$/,/^\[/ s/^prompt = .*/prompt = "◷ folders> "/' "$DHOME/.config/fist/config.toml"
# Native image preview through the sixel path (CommandSpace renders it).
sed -i 's/^# protocol = "auto"/protocol = "sixel"/' "$DHOME/.config/fist/mm.toml"
cat >> "$DHOME/.config/fist/config.toml" <<'EOF'

[panes.stashes.bookmark]
kind = "prune"
insert = "skip"

# A deliberately small copy buffer so the long-copy clip's queue bar runs
# long enough to watch (1.5 KiB vs the 512 KiB default).
[queue.copy]
buffer_size = 1536
EOF
# Keep completed queue rows after the overlay closes, so the queue-edit clip
# can reopen the queue and re-run a finished row.
sed -i 's/^# clear_completed_on_close = true/clear_completed_on_close = true/' \
  "$DHOME/.config/fist/config.toml"
# Info scene: a full-width top preview so mediainfo labels and values fit.
sed 's/^\[panes.nav\]$/[panes.nav]\npreview_layout_index = 1/' \
  "$DHOME/.config/fist/config.toml" > "$DHOME/.config/fist/config-info.toml"

# ---- CommandSpace config ----
cp "$TOOLS/commandspace.toml" "$DHOME/.config/commandspace/config.toml"

# Demo shell for the shell-integration clip. The integration is evaluated
# inside the sandbox so the generated script embeds the sandbox fs path.
cat > "$DHOME/.bashrc" <<'EOF'
eval "$(/home/dev/repo/fist/fs :tool shell --shell bash --aliases)"
PS1='\w $ '
# bind -x captures a widget's stdout; send the rg pane's to the tty so
# Advance can launch the editor.
__fist_rg_widget() {
  /home/dev/repo/fist/fs :rg -1 --fullscreen --style=colors --preserve-whitespace >/dev/tty
}
EOF

# ---- demo world ----
mkdir -p "$W"/harborlight/{src/api,src/ui,src/cli,migrations,docs,scripts,logs,tests,benches,config,node_modules,target/debug} \
  "$W"/vault/{projects,meetings,inbox} \
  "$W"/media/{photos,audio,video} \
  "$W"/data "$W"/archive "$W"/inbox

# The app's own source tree, visible to the Search pane. The target is
# bind-mounted inside the capture namespace; on the host this link is dangling.
ln -sfn /home/dev/repo/fist-src "$W/fist"

cd "$W/harborlight"
git init -q
printf 'target/\nnode_modules/\n.env\nlogs/\n' > .gitignore
printf '[package]\nname = "harborlight"\nversion = "0.9.0"\nedition = "2021"\n' > Cargo.toml
printf '# This file is automatically @generated by Cargo.\nversion = 3\n' > Cargo.lock
printf '# Harborlight\n\nA small archival service.\n' > README.md
printf 'DATABASE_URL=postgres://localhost/harborlight\nAPI_KEY=dev-secret\n' > .env
printf 'DATABASE_URL=postgres://localhost/harborlight\n' > .env.example
printf 'version = 4\n' > rust-toolchain.toml
printf 'FROM rust:1-slim\nWORKDIR /app\nCOPY . .\nRUN cargo build --release\n' > Dockerfile
printf 'run:\n\tcargo run --release\n\ncheck:\n\tcargo clippy --all-targets\n' > Makefile
printf 'services:\n  db:\n    image: postgres:16\n    environment:\n      POSTGRES_DB: harborlight\n' > docker-compose.yml
printf 'MIT License\n\nCopyright (c) 2024 Harborlight contributors\n' > LICENSE
printf 'pub mod api;\n\nfn main() {\n    println!("harborlight");\n}\n' > src/main.rs
printf 'pub fn connect() { /* TODO: pool */ }\n' > src/db.rs
printf 'pub struct Config { pub port: u16 }\n' > src/config.rs
printf 'pub mod routes;\npub mod auth;\n' > src/api/mod.rs
printf '// GET /health returns 200\npub fn health() -> u16 { 200 }\n' > src/api/routes.rs
printf '// TODO(team): rotate keys before release\npub fn verify(token: &str) -> bool { !token.is_empty() }\n' > src/api/auth.rs
printf 'import { useEffect, useState } from "react";\n\nexport function App() {\n  const [ready, setReady] = useState(false);\n  useEffect(() => setReady(true), []);\n  return <main>{ready ? "ready" : "loading"}</main>;\n}\n' > src/ui/App.tsx
printf 'package main\n\nimport "fmt"\n\nfunc main() {\n\tfmt.Println("harborlight")\n}\n' > src/cli/main.go
printf '#!/usr/bin/env python3\nimport os\n\nprint("deploy", os.getenv("HARBORLIGHT_ENV", "staging"))\n' > scripts/deploy.py
chmod +x scripts/*.py
printf 'server:\n  port: 8080\n  workers: 4\n' > config/app.yaml
printf '%s\n' '%PDF-1.4' '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj' '2 0 obj << /Type /Pages /Kids [] /Count 0 >> endobj' 'trailer << /Root 1 0 R >>' '%%EOF' > docs/whitepaper.pdf
printf 'CREATE TABLE users (id INTEGER PRIMARY KEY);\n' > migrations/0001_init.sql
printf 'CREATE TABLE sessions (id INTEGER PRIMARY KEY);\n' > migrations/0002_sessions.sql
printf '# Architecture\n\nThe gateway owns auth. Requests arrive through the edge proxy and are routed\nto the ingest or query service.\n\n- ingest appends to a segmented log\n- query reads compacted segments\n- the compactor runs on the archive worker\n' > docs/architecture.md
printf '# API\n\n## `POST /v1/ingest`\n\nAccepts a batch of records. Returns `202` once the batch is durable.\n\n## `GET /v1/segments/:id`\n\nStreams a compacted segment. Requires `read:segments`.\n' > docs/api.md
printf '# Changelog\n\n## 0.9.0 - initial\n\n- segmented log\n- gateway auth\n- nightly compaction\n' > docs/changelog.md
# Stable docs mtimes and a two-row cursor selection for the compress clip.
# Tab selects the first two visible rows (currently api.md and changelog.md).
touch -d '2026-10-30 14:20:00' docs/architecture.md
touch -d '2026-10-30 14:19:00' docs/api.md
touch -d '2026-10-30 14:18:00' docs/changelog.md
touch -d '2026-10-30 14:17:00' docs/whitepaper.pdf
printf '#!/bin/sh\ncargo build --release\n' > scripts/release.sh
printf '#!/bin/sh\npsql -f migrations/0001_init.sql\n' > scripts/seed.sh
chmod +x scripts/*.sh
printf 'INFO listening on :8080\nINFO db connected\n' > logs/app.log
printf 'ERROR refused connection to postgres\n' > logs/app.log.1
printf 'WARN slow query 1200ms\n' > logs/error.log
printf '// smoke tests\n\n#[test]\nfn health_is_ok() {\n    assert_eq!(harborlight::api::routes::health(), 200);\n}\n' > tests/smoke.rs
printf '// ingest benchmarks\n\nfn main() {\n    println!("ingest benchmark");\n}\n' > benches/ingest.rs
head -c 4000000 /dev/zero > target/debug/harborlight
# Stable nav order: the first two rows of the hero/options scenes.
touch -d '2026-10-30 14:10:00' .env.example
touch -d '2026-10-30 14:09:00' src
for f in * .[!.]*; do
  [ "$f" = .env.example ] || [ "$f" = src ] || touch -d '2026-10-30 14:00:00' "$f" 2>/dev/null || true
done
# Shell-integration clip: a committed repo plus one pre-edited file so the
# `git add` beat stages two changes.
git add -A
git -c user.name='Harborlight' -c user.email='dev@harborlight.test' \
  commit -qm 'Initial import'
printf '\n// pool size tuned in staging\n' >> src/db.rs

printf '# Harborlight notes\n' > "$W/vault/projects/harborlight.md"
cat > "$W/vault/projects/harborlight.md" <<'EOF'
