P=$W/media/photos
fetch() {
  id=$1; size=$2; dest=$3
  if [ ! -f "$CACHE/$dest" ]; then
    curl -fsSL --retry 2 --max-time 40 "https://picsum.photos/id/$id/$size" -o "$CACHE/$dest"
  fi
}
